"""Write Modules/Combat/ImpairData.lua: the spells that slow or root, per client.

    python tools/make_impairing.py            write it from the cached tables
    python tools/make_impairing.py --check    exit 1 when it is not what they give

A spell slows or roots when one of its effects applies aura 26 (root) or 33
(a decrease in movement speed): what Blessing of Freedom takes off. The tables
are the SpellEffect ones tools/audit_ids.py downloads (default
%TEMP%/manners-audit-cache; `python tools/audit_ids.py --fetch-only`), the
newest cached build of each client. The combat prompt's `impaired` check
(Modules/Combat/MomentsSense.lua) reads a friendly target's debuffs against it.
"""

import argparse
import csv
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Modules", "Combat", "ImpairData.lua")
CLIENTS = ("camelot", "vanilla", "tbc", "mists", "mainline")
AURAS = {"26", "33"}


def newest(cache, client):
    files = sorted(glob.glob(os.path.join(cache, "%s@*_SpellEffect.csv" % client)))
    if not files:
        raise SystemExit("no cached SpellEffect for %s in %s -- python tools/audit_ids.py --fetch-only" % (client, cache))
    return files[-1]


def spells(path):
    out = set()
    with open(path, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            if row.get("EffectAura") in AURAS:
                out.add(int(row["SpellID"]))
    return sorted(out)


def render(cache):
    lines = [
        "-- Manners -- the spells that slow or root (aura 26 or 33 on an effect), per",
        "-- client: what Blessing of Freedom takes off. Generated by",
        "-- tools/make_impairing.py from each client's SpellEffect table; never edited",
        "-- by hand. Builds:",
    ]
    data = {}
    for client in CLIENTS:
        path = newest(cache, client)
        build = os.path.basename(path).split("@", 1)[1].split("_", 1)[0]
        data[client] = spells(path)
        lines.append("--   %-8s %s, %d spells" % (client, build, len(data[client])))
    lines += ["", "local ns = assert(MannersAPI and MannersAPI:ModuleContext(\"combat\"), \"Manners module API is missing\")", "",
              "local function Set(ids)", "\tlocal set = {}", "\tfor _, id in ipairs(ids) do set[id] = true end", "\treturn set", "end", "",
              "ns.IMPAIRING_BY_CLIENT = {"]
    for client in CLIENTS:
        ids = data[client]
        lines.append("\t%s = function() return Set {" % client)
        for i in range(0, len(ids), 12):
            lines.append("\t\t" + ", ".join(str(x) for x in ids[i:i + 12]) + ",")
        lines.append("\t} end,")
    lines += ["}", "local flavour = ns.Flavour and ns.Flavour.flavour",
              "local build = ns.IMPAIRING_BY_CLIENT[flavour]", "ns.IMPAIRING = build and build() or {}", "ns.IMPAIRING_BY_CLIENT = nil", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cache", default=os.path.join(os.environ.get("TEMP", "."), "manners-audit-cache"))
    args = parser.parse_args()
    text = render(args.cache)
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("ImpairData.lua is current" if current == text else "ImpairData.lua is not what the tables give")
        return 0 if current == text else 1
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote " + os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())