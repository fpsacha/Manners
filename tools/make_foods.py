"""Write Foods.lua: every item that gives the "Well Fed" aura, per client.

    python tools/make_foods.py            write Foods.lua from the cached tables
    python tools/make_foods.py --check    say whether the shipped Foods.lua is current
                                          for the builds it was made from (its header)
    python tools/make_foods.py --cache DIR  where the wago.tools CSVs live

The tables are the ones tools/audit_ids.py downloads (default
%TEMP%/manners-audit-cache; fetch them with `python tools/audit_ids.py
--fetch-only`). An item gives Well Fed when a spell it uses is named "Well Fed"
or has an effect that triggers one: that is how every client's food does it.
Each client lists the item, the level it asks of the player and the spell the
use casts (the one the press settles on), best first: the highest level, then
the lowest item id, so the order is the same on every run.

Nothing here ships: the output does, and Foods.lua is held to its own shape by
tests/scenarios/wellfed.lua, which never needs the cache.
"""

import argparse
import collections
import csv
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Foods.lua")

# The client keys the addon uses (Buffs.lua SETS), and the tables each reads. Retail's
# food is a different system (feasts, the same aura under a hundred names) and is not
# offered: its set has no own buffs but a rogue's poisons.
CLIENTS = ("camelot", "vanilla", "tbc", "mists")
# Forever and retail link an item to its effects through ItemXItemEffect; the
# Classic clients carry the item on the effect row itself.
VIA_LINK_TABLE = {"camelot"}
# The Well Fed spell a client's name is read from, when it has it: 19705 is the
# first of them on every client.
PREFERRED_WELL_FED = 19705


# The build each client's tables are read at, when not the newest cached: --check
# pins them to the ones the shipped Foods.lua names in its header.
PINNED = {}


def header_builds(text):
    """{client: build} from the "Builds:" lines of a Foods.lua header."""
    return dict(re.findall(r"^--\s+(\w+)\s+([0-9][0-9.]*), \d+ foods$", text, re.M))


def newest(cache, client, table):
    build = PINNED.get(client)
    files = sorted(glob.glob(os.path.join(cache, "%s@%s_%s.csv" % (client, build or "*", table))))
    if not files:
        raise SystemExit("no cached %s for %s in %s -- python tools/audit_ids.py --fetch-only" % (table, client, cache))
    return files[-1]


def rows(cache, client, table):
    path = newest(cache, client, table)
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f)), os.path.basename(path)


def build_of(filename):
    return filename.split("@", 1)[1].split("_", 1)[0]


def foods(cache, client):
    names_rows, names_file = rows(cache, client, "SpellName")
    names = {r["ID"]: r["Name_lang"] for r in names_rows}
    well_fed = {i for i, n in names.items() if n == "Well Fed"}
    triggers = collections.defaultdict(set)
    for r in rows(cache, client, "SpellEffect")[0]:
        t = r.get("EffectTriggerSpell")
        if t and t in well_fed:
            triggers[r["SpellID"]].add(t)
    effect_rows = rows(cache, client, "ItemEffect")[0]
    item_spells = collections.defaultdict(list)
    if client in VIA_LINK_TABLE:
        by_id = {r["ID"]: r for r in effect_rows}
        for r in rows(cache, client, "ItemXItemEffect")[0]:
            e = by_id.get(r["ItemEffectID"])
            if e:
                item_spells[r["ItemID"]].append(e["SpellID"])
    else:
        for r in effect_rows:
            item_spells[r["ParentItemID"]].append(r["SpellID"])
    levels = {r["ID"]: int(r["RequiredLevel"] or 0) for r in rows(cache, client, "ItemSparse")[0]}
    out = []
    for item, spells in item_spells.items():
        # The spell the item uses and that leads to Well Fed: the first of them.
        use = next((int(s) for s in spells if s in well_fed or s in triggers), None)
        if use is not None and item in levels:
            out.append((int(item), levels[item], use))
    out.sort(key=lambda row: (-row[1], row[0]))
    fed = PREFERRED_WELL_FED if str(PREFERRED_WELL_FED) in well_fed else min(int(i) for i in well_fed)
    return out, fed, build_of(names_file)


def render(cache):
    lines = [
        "-- Manners -- the food that gives Well Fed, per client.",
        "--",
        "-- Generated by tools/make_foods.py from each client's own item and spell data",
        "-- (wago.tools): never edited by hand. Every row is { item, the level it asks",
        "-- of the player, the spell its use casts }, best first. `fed` is a spell of",
        "-- the \"Well Fed\" aura on that client, whose localised name is how the aura is",
        "-- read. Builds:",
    ]
    tables = {}
    for client in CLIENTS:
        tables[client] = foods(cache, client)
        lines.append("--   %-8s %s, %d foods" % (client, tables[client][2], len(tables[client][0])))
    lines += ["", "local _, ns = ...", "", "ns.FOODS = {"]
    for client in CLIENTS:
        items, fed, _ = tables[client]
        lines.append("\t%s = {" % client)
        lines.append("\t\tfed = %d," % fed)
        for item, level, use in items:
            lines.append("\t\t{ %d, %d, %d }," % (item, level, use))
        lines.append("\t},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when Foods.lua is not what the tables give")
    parser.add_argument("--cache", default=os.path.join(os.environ.get("TEMP", "."), "manners-audit-cache"))
    args = parser.parse_args()
    current = None
    if args.check:
        current = open(OUT, encoding="utf-8", newline="").read() if os.path.exists(OUT) else None
        if current:
            PINNED.update(header_builds(current))
    text = render(args.cache)
    if args.check:
        if current == text:
            print("Foods.lua is current")
            return 0
        print("Foods.lua is not what the tables give: python tools/make_foods.py")
        return 1
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote Foods.lua: " + ", ".join("%s %d" % (c, len(foods(args.cache, c)[0])) for c in CLIENTS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
