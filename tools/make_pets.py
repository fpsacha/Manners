"""Write Pets.lua: the companion pets used from the bags, per client.

    python tools/make_pets.py            write Pets.lua from the cached tables
    python tools/make_pets.py --check    say whether the shipped Pets.lua is current
                                         for the builds it was made from (its header)
    python tools/make_pets.py --cache DIR  where the wago.tools CSVs live

The tables are the ones tools/audit_ids.py downloads (default
%TEMP%/manners-audit-cache; fetch them with `python tools/audit_ids.py
--fetch-only`). A companion pet is summoned by a spell with a SUMMON effect
(SpellEffect.Effect 28) whose SummonProperties row is the companion's
(Slot 5, Title 5): nothing else uses that slot with that title on these
clients. An item is listed when its use (ItemEffect.TriggerType 0) casts one
of those spells and it is used from the bags each time:

  - not an item that teaches the pet (Forever's journal pets: the item is used
    up once, and the pet journal summons it after; Manners reads the journal
    for those, Core.lua);
  - not an item worn to be used (InventoryType other than 0: the Bloodsail
    Admiral's Hat);
  - not an item only some classes may use (the mage's familiar scrolls on
    Forever, a family of the mage's own in Buffs.lua).

Each row is { item, the level it asks of the player, the spell its use casts },
by item id. Classic Era and Burning Crusade use every pet from the bags;
Forever a handful; Mists and retail none, which is why they are not listed.

Nothing here ships: the output does, and Pets.lua is held to its own shape by
tests/scenarios/pets.lua, which never needs the cache.
"""

import argparse
import collections
import csv
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Pets.lua")

CLIENTS = ("camelot", "vanilla", "tbc")
# Forever links an item to its effects through ItemXItemEffect; the Classic
# clients carry the item on the effect row itself.
VIA_LINK_TABLE = {"camelot"}
SUMMON = "28"
ON_USE = "0"
# Every class's bit, as an item's AllowableClass may spell "anybody".
ANYBODY = {"", "-1", "0", "32767", "4095", "2047", "1535"}

PINNED = {}


def header_builds(text):
    """{client: build} from the "Builds:" lines of a Pets.lua header."""
    return dict(re.findall(r"^--\s+(\w+)\s+([0-9][0-9.]*), \d+ pets$", text, re.M))


def newest(cache, client, table):
    build = PINNED.get(client)
    files = sorted(glob.glob(os.path.join(cache, "%s@%s_%s.csv" % (client, build or "*", table))))
    if not files:
        raise SystemExit("no cached %s for %s in %s -- python tools/audit_ids.py --fetch-only" % (table, client, cache))
    return files[-1]


def rows(cache, client, table):
    path = newest(cache, client, table)
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f)), os.path.basename(path)


def build_of(filename):
    return filename.split("@", 1)[1].split("_", 1)[0]


def pets(cache, client):
    companion = {r["ID"] for r in rows(cache, client, "SummonProperties")[0]
                 if r["Slot"] == "5" and r["Title"] == "5"}
    effects, effects_file = rows(cache, client, "SpellEffect")
    summons = {r["SpellID"] for r in effects if r["Effect"] == SUMMON and r["EffectMiscValue_1"] in companion}
    effect_rows = rows(cache, client, "ItemEffect")[0]
    item_effects = collections.defaultdict(list)
    if client in VIA_LINK_TABLE:
        by_id = {r["ID"]: r for r in effect_rows}
        for r in rows(cache, client, "ItemXItemEffect")[0]:
            e = by_id.get(r["ItemEffectID"])
            if e:
                item_effects[r["ItemID"]].append(e)
    else:
        for r in effect_rows:
            item_effects[r["ParentItemID"]].append(r)
    sparse = {r["ID"]: r for r in rows(cache, client, "ItemSparse")[0]}
    out = []
    for item, list_ in item_effects.items():
        info = sparse.get(item)
        if info is None:
            continue
        uses = [e for e in list_ if e["SpellID"] in summons and e["TriggerType"] == ON_USE]
        if not uses:
            continue
        # An item that also teaches (a learn trigger, or the "Learning" spell) is a journal pet.
        if any(e["TriggerType"] == "6" or e["SpellID"] == "55884" for e in list_):
            continue
        if (info.get("InventoryType") or "0") != "0":
            continue
        if (info.get("AllowableClass") or "-1") not in ANYBODY:
            continue
        out.append((int(item), int(info.get("RequiredLevel") or 0), int(uses[0]["SpellID"])))
    out.sort()
    return out, build_of(effects_file)


def render(cache):
    lines = [
        "-- Manners -- the companion pets used from the bags, per client.",
        "--",
        "-- Generated by tools/make_pets.py from each client's own item and spell data",
        "-- (wago.tools): never edited by hand. Every row is { item, the level it asks",
        "-- of the player, the spell its use casts }, by item id. Builds:",
    ]
    tables = {}
    for client in CLIENTS:
        tables[client] = pets(cache, client)
        lines.append("--   %-8s %s, %d pets" % (client, tables[client][1], len(tables[client][0])))
    lines += ["", "local _, ns = ...", "", "ns.PETS = {"]
    for client in CLIENTS:
        lines.append("\t%s = {" % client)
        for item, level, use in tables[client][0]:
            lines.append("\t\t{ %d, %d, %d }," % (item, level, use))
        lines.append("\t},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when Pets.lua is not what the tables give")
    parser.add_argument("--cache", default=os.path.join(os.environ.get("TEMP", "."), "manners-audit-cache"))
    args = parser.parse_args()
    current = None
    if args.check:
        current = open(OUT, encoding="utf-8", newline="").read() if os.path.exists(OUT) else None
        if current:
            PINNED.update(header_builds(current))
    text = render(args.cache)
    if args.check:
        if current == text:
            print("Pets.lua is current")
            return 0
        print("Pets.lua is not what the tables give: python tools/make_pets.py")
        return 1
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote Pets.lua: " + ", ".join("%s %d" % (c, len(pets(args.cache, c)[0])) for c in CLIENTS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
